"""Compact results summary for the README, built only from saved run and evaluation files (no model calls).

`python -m pipeline results --run-id final100k --readme README.md` rewrites the block between the
RESULTS markers, so every number in it is copied from an artifact rather than typed by hand.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime
from pathlib import Path

from .common import ROOT

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _hours(invocations: list[dict]) -> float:
    total = 0.0
    for inv in invocations:
        if inv.get("started_at") and inv.get("ended_at"):
            total += (datetime.fromisoformat(inv["ended_at"]) - datetime.fromisoformat(inv["started_at"])).total_seconds()
    return total / 3600


def build_results(run_dir: Path) -> str:
    s = _json(run_dir / "run_summary.json")
    ing = _json(run_dir / "ingestion_report.json") or {}
    ver = _json(run_dir / "verify" / "verify_summary.json")
    memo = _json(run_dir / "memo_checks.json") or {}
    gold = _json(ROOT / "evals" / "golden" / "golden_summary.json")
    planted = _json(ROOT / "evals" / "planted_errors.json")
    inj = _json(ROOT / "evals" / "injection" / "results.json")
    check = _json(ROOT / "runs" / "_orchestrator" / "self-check.json")
    check = check[0] if isinstance(check, list) else check
    cov, prof = s["coverage"], (ing.get("official_profile") or {}).get("counts", {})
    src = s.get("result_sources", {})
    reused = sum(v for k, v in src.items() if k != "model_call")
    calls = s.get("calls_by_role_model_tier", {})
    attempts = sum(v["attempts"] for v in calls.values())
    failed = sum(v["failed"] for v in calls.values())
    out_tok = sum(v["output_tokens"] for v in calls.values())
    in_tok = sum(v["input_tokens"] + v.get("cache_read_input_tokens", 0) for v in calls.values())
    call_log = run_dir / "calls.jsonl"
    call_hours = (sum((json.loads(line).get("duration_s") or 0) for line in call_log.read_text().splitlines()
                      if line.strip()) / 3600) if call_log.exists() else None
    invocations = s.get("invocations", [])
    elapsed = _hours(invocations)
    unfinished = sum(1 for inv in invocations if not inv.get("ended_at"))
    lc = (_json(ROOT / "cost" / "assumptions.json") or {}).get("local_compute", {})
    kwh = (call_hours if call_hours is not None else elapsed) * lc.get("watts_under_load", 0) / 1000
    with (run_dir / "ranking.csv").open(encoding="utf-8", newline="") as f:
        top = list(csv.DictReader(f))[:5]
    L = [START, "## Results (final run)\n",
         f"Generated by `python -m pipeline results` from `runs/{run_dir.name}/` and `evals/`. Measured values only; "
         "estimates are labeled.\n",
         "| item | value |", "|---|---|",
         f"| source file profiled | {prof.get('records', 'n/a'):,} rows · {prof.get('empty_review_text', 'n/a')} empty texts · "
         f"{prof.get('missing_app_version', 'n/a'):,} missing app versions · {prof.get('duplicate_review_ids', 'n/a')} duplicate IDs |",
         f"| analysis scope (declared subset) | {cov['rows']:,} rows |",
         f"| completed classifications | **{cov['completed']:,}** |",
         f"| quarantined | {cov['quarantined']:,} ({cov['quarantine_reasons']}) |",
         f"| pending (unfinished) | {cov['pending']:,} |",
         f"| labeled by a model call / reused exact-text results | {src.get('model_call', 0):,} / {reused:,} ({src}) |",
         f"| complaints + cancellations (ranked) | {cov['complaints']:,} (cancellations {cov['cancellations']:,}) |",
         f"| flagged needs_review | {s.get('needs_review', 0):,} |",
         f"| model calls (attempts, incl. failures) | {attempts:,} attempts, {failed:,} failed |",
         f"| tokens (input incl. cached / output) | {in_tok:,} / {out_tok:,} |",
         f"| API spend | **${s.get('spend_usd_actual', 0):.2f}** (local model; budget cap ${s.get('budget_usd', 0):.2f}) |",
         f"| elapsed time across invocations | {elapsed:.1f} h over {len(invocations)} invocation(s)"
         f"{f', {unfinished} ended without a clean stop (process killed) and is not timed' if unfinished else ''}; "
         f"includes laptop sleep pauses. Summed model-call time "
         f"{'n/a' if call_hours is None else f'{call_hours:.1f} h'} (sleep excluded) |",
         f"| local electricity (estimate) | ≈ ${kwh * lc.get('usd_per_kwh', 0):.2f} for the model-call time at {lc.get('watts_under_load')} W, "
         f"${lc.get('usd_per_kwh')}/kWh (assumptions) |",
         f"| memo automated claim check | {memo.get('status', 'n/a')} |"]
    if ver:
        L.append(f"| independent verifier (n={ver['verified']}) | topic {_pct(ver['topic_agree_rate'])} · intent "
                 f"{_pct(ver['intent_agree_rate'])} · severity exact {_pct(ver['severity_exact_rate'])} / ±1 "
                 f"{_pct(ver['severity_within_1_rate'])} · {ver['disagreements']} disagreements |")
    if gold:
        a = gold["agreement"]
        L.append(f"| golden 50 vs human labels | topic {_pct(a['topic'])} · intent {_pct(a['intent'])} · severity exact "
                 f"{_pct(a['severity'])} (±1 {_pct(gold['severity_within_1'])}, MAE {gold['severity_mae']}) · all three "
                 f"{_pct(a['joint'])} · sentiment MAE {gold['sentiment_mae']} · macro F1 topic {gold['topic_macro_f1']} / "
                 f"intent {gold['intent_macro_f1']} · {gold['ambiguous_cases']} ambiguous · "
                 f"{gold['missing_or_quarantined_predictions']} missing |")
    else:
        L.append("| golden 50 vs human labels | *not evaluated yet* |")
    if planted:
        L.append(f"| planted-error test (synthetic) | {planted['flagged']} of {planted['planted']} planted errors flagged |")
    if inj:
        L.append(f"| injection test (synthetic) | controls {inj.get('control_cases_passed')}/4 correct · injected labels "
                 f"{inj.get('injection_label_passed')}/{inj.get('injection_cases')} correct · injected flagged for review "
                 f"{inj.get('injection_flagged_for_review')}/{inj.get('injection_cases')} |")
    if check:
        L.append(f"| course self-check (`check_submission.py`) | status `{check.get('status')}` · coverage point candidate "
                 f"{check.get('working_coverage_point_candidate')} · issues {check.get('issue_counts') or 'none'} |")
    L += ["\nTop of the baseline ranking (priority = severity_sum):\n", "| rank | issue | complaints | severity sum | mean |",
          "|---|---|---|---|---|"]
    L += [f"| {r['rank']} | `{r['issue_id']}` | {int(r['complaint_count']):,} | {int(r['severity_sum']):,} | "
          f"{float(r['mean_severity']):.2f} |" for r in top]
    L.append(END)
    return "\n".join(L)


def update_readme(readme: Path, block: str) -> None:
    text = readme.read_text(encoding="utf-8")
    if START in text and END in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        anchor = "## Contents"
        text = text.replace(anchor, block + "\n\n" + anchor, 1) if anchor in text else text + "\n" + block + "\n"
    readme.write_text(text, encoding="utf-8")
